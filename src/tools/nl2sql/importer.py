"""Administrative approved-JSON importer. Run with --help; never registered as an MCP tool."""

import argparse
import asyncio
import logging
import os
import uuid
from contextlib import AsyncExitStack
from pathlib import Path

from azure.core import MatchConditions
from azure.cosmos.aio import CosmosClient
from azure.cosmos.exceptions import CosmosResourceNotFoundError
from azure.identity.aio import ManagedIdentityCredential
from pydantic import Field, model_validator

from .catalog import float32_vector
from .config import load_settings
from .contracts import Metadata, Source, StrictModel
from .models import Models


class ImportFile(StrictModel):
    source: Source
    records: list[Metadata] = Field(min_length=1, max_length=256)

    @model_validator(mode="after")
    def complete_catalog(self):
        approved = set(self.source.allowed_objects)
        schemas = set()
        ids = set()
        for record in self.records:
            if record.source_id != self.source.source_id:
                raise ValueError("All records must match source_id")
            if record.metadata_version != self.source.metadata_version:
                raise ValueError("All records must match metadata_version")
            if record.id in ids or record.embedding:
                raise ValueError("Record IDs must be unique and embeddings generated by importer")
            ids.add(record.id)
            if record.object_name and record.object_name not in approved:
                raise ValueError("Record object must be approved")
            if not set(record.related_objects) <= approved:
                raise ValueError("Related objects must be approved")
            if record.kind == "schema":
                if not record.object_name:
                    raise ValueError("Schema records must identify an approved object")
                schemas.add(record.object_name)
        if schemas != approved:
            raise ValueError(
                "Every approved object requires schema context, including FK relationships"
            )
        if sum(len(r.content) for r in self.records) > 64000:
            raise ValueError("Complete catalog context exceeds 64000 characters")
        return self


async def import_metadata(data, sources, metadata, models, dimensions):
    """Stage a unique immutable version; CAS-activate only after every write is persisted."""
    try:
        previous = await sources.read_item(data.source.id, partition_key=data.source.source_id)
    except CosmosResourceNotFoundError:
        previous = None
    # Allocate a unique physical version so retries/concurrent imports cannot mutate active records.
    version = f"{data.source.metadata_version[:95]}-{uuid.uuid4().hex}"
    for record in data.records:
        document = record.model_dump()
        document["metadata_version"] = version
        document["id"] = f"{uuid.uuid4().hex}-{record.id[:95]}"
        document["embedding"] = float32_vector(await models.embed(record.content), dimensions)
        await metadata.create_item(document)
    document = data.source.model_dump()
    document["metadata_version"] = version
    if previous is None:
        await sources.create_item(document)
    else:
        await sources.replace_item(
            data.source.id,
            document,
            etag=previous["_etag"],
            match_condition=MatchConditions.IfNotModified,
        )
    return version


async def run(path):
    if path.stat().st_size > 2 * 1024 * 1024:
        raise ValueError("Approved import JSON exceeds 2 MiB")
    data = ImportFile.model_validate_json(path.read_text(encoding="utf-8"))
    async with AsyncExitStack() as stack:
        credential = await stack.enter_async_context(
            ManagedIdentityCredential(client_id=os.getenv("AZURE_CLIENT_ID"))
        )
        settings = await load_settings(credential)
        if data.source.authentication == "sql_password" and (
            not settings.KEY_VAULT_ENDPOINT
            or data.source.password_secret_name not in settings.MCP_SQL_SECRET_NAMES
        ):
            raise ValueError("Password source requires approved secret name and Key Vault endpoint")
        cosmos = await stack.enter_async_context(
            CosmosClient(str(settings.MCP_COSMOS_ENDPOINT), credential=credential)
        )
        database = cosmos.get_database_client(settings.MCP_COSMOS_DATABASE)
        models = Models(settings, credential)
        stack.push_async_callback(models.close)
        return await import_metadata(
            data,
            database.get_container_client(settings.MCP_SOURCES_CONTAINER),
            database.get_container_client(settings.MCP_METADATA_CONTAINER),
            models,
            settings.MCP_EMBEDDING_DIMENSIONS,
        )


def main():
    parser = argparse.ArgumentParser(
        description="Import operator-approved SQL schema/examples; activate only a complete version.",
        epilog="Requires APP_CONFIG_ENDPOINT and managed identity (optional AZURE_CLIENT_ID); "
        "agent-lz App Configuration, Cosmos write and model inference permissions. "
        "Does not create Azure resources. Supply schema/FK context, never business rows.",
    )
    parser.add_argument(
        "--file", required=True, type=Path, help="Approved source/records JSON file"
    )
    args = parser.parse_args()
    try:
        version = asyncio.run(run(args.file))
    except Exception as exc:
        logging.error(
            "Import failed (%s); activation not confirmed. Read source to confirm active version.",
            type(exc).__name__,
        )
        raise SystemExit(1) from None
    print(f"Activated metadata_version: {version}")


if __name__ == "__main__":
    main()
